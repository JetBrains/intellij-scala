import java.io.File
import java.nio.file.Files
import scala.io.Source

/** Shared by both meta-builds and the tools build; keep compatible with Scala 2.12. */
final case class TestBucketAllocation(bucketCount: Int, assignments: Map[String, Int]) {
  require(bucketCount > 0, "The number of test buckets must be positive")
  require(assignments.keys.forall(name => name.nonEmpty && !name.exists(_.isWhitespace)), "Invalid test class name")
  require(assignments.values.forall(bucket => bucket >= 0 && bucket < bucketCount), "Test bucket out of range")

  def bucket(testClassName: String, totalBuckets: Int): Option[Int] = {
    // An allocation for a different count cannot be used as-is: some tests would never run.
    if (totalBuckets == bucketCount)
      assignments.get(testClassName)
    else None
  }

  def render: String = {
    val rows = assignments.toVector.sortBy(_._1).map { case (name, bucket) => s"$bucket\t$name" }
    (Vector("# Generated by tools/run GenerateTestBucketAllocation", s"buckets\t$bucketCount") ++ rows).mkString("", "\n", "\n")
  }
}

object TestBucketAllocation {
  val FileName = "TestBucketAllocation.tsv"

  /** Ultimate contains the Community build in community/; Community can also be built on its own. */
  def fileIn(buildRoot: File): File = {
    val community = new File(buildRoot, "community")
    val communityRoot = if (community.isDirectory) community else buildRoot
    new File(new File(communityRoot, "project"), FileName)
  }

  /** Missing files use hashing. Malformed files fail the build rather than silently changing assignments. */
  def load(file: File): Either[String, TestBucketAllocation] = {
    if (Files.notExists(file.toPath)) Left(s"File $file does not exist")
    else {
      val source = Source.fromFile(file, "UTF-8")
      try Right(parse(source.mkString))
      catch {
        case e: IllegalArgumentException =>
          Left(s"Invalid test bucket allocation in $file: ${e.getMessage}")
      }
      finally source.close()
    }
  }

  def parse(text: String): TestBucketAllocation = {
    val lines = text.split("\n").iterator.map(_.trim).filter(line => line.nonEmpty && !line.startsWith("#")).toVector
    require(lines.nonEmpty, "Missing bucket count")
    val header = lines.head.split("\t", -1)
    require(header.length == 2 && header(0) == "buckets", "Expected a buckets<TAB>count header")
    val bucketCount = header(1).toInt
    val entries = lines.tail.map { line =>
      val fields = line.split("\t", -1)
      require(fields.length == 2, s"Expected bucket<TAB>class, got: $line")
      fields(1) -> fields(0).toInt
    }
    require(entries.map(_._1).distinct.size == entries.size, "Duplicate test class assignment")
    TestBucketAllocation(bucketCount, entries.toMap)
  }
}
